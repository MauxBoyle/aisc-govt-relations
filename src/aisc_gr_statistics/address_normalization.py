def normalize_text(value: str) -> str:
    """Uppercase, replace punctuation with spaces, and collapse whitespace."""
    return " ".join(re.sub(r"[^\w\s]", " ", value.upper()).split())


def normalize_street(value: str) -> str:
    """Apply C1 only at the suffix position and C2 only after that suffix."""
    words = normalize_text(value).split()
    suffix_index = len(words) - 1 if words and words[-1] in STREET_SUFFIXES else -1
    if suffix_index == -1:
        # A suffix can be followed by a C2 designator and its unit detail.
        suffix_index = next(
            (
                index
                for index in range(len(words) - 2, -1, -1)
                if words[index] in STREET_SUFFIXES
                and words[index + 1] in UNIT_DESIGNATORS
            ),
            -1,
        )
    if suffix_index != -1:
        words[suffix_index] = STREET_SUFFIXES[words[suffix_index]]
        if suffix_index + 1 < len(words) and words[suffix_index + 1] in UNIT_DESIGNATORS:
            words[suffix_index + 1] = UNIT_DESIGNATORS[words[suffix_index + 1]]
    return " ".join(words)


def normalize_zip(value: str) -> str:
    """Return ZIP5 when it is present, discarding a ZIP+4 extension."""
    match = re.search(r"\b(\d{5})(?:-\d{4})?\b", value)
    return match.group(1) if match else ""
