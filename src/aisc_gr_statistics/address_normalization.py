"""Deterministic USPS-style formatting used for Census address lookups.

The tables below are a checked-in transcription of the USPS Publication 28
Appendix C1 (street suffixes) and C2 (secondary unit designators) standard
abbreviations.  They intentionally do not validate or correct an address.
"""

import re


def _table(rows: str) -> dict[str, str]:
    """Turn compact ``variants:standard`` rows into a lookup dictionary."""
    result: dict[str, str] = {}
    for row in rows.strip().splitlines():
        variants, standard = row.split(":")
        for variant in variants.split(","):
            result[variant.strip()] = standard.strip()
    return result


